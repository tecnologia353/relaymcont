-- =============================================================================
-- Relay — esquema do banco (PostgreSQL / Supabase)
--
-- Compatível com os modelos SQLAlchemy em backend/app/models/entities.py e
-- com os campos que o frontend já usa (lib/api.ts): convites, processo de
-- origem da tarefa, prazos das etapas etc.
--
-- Datas em `timestamp` (sem fuso, em UTC) porque o backend compara com
-- datetime.utcnow() ingênuo.
--
-- Rode inteiro no SQL Editor do Supabase. Pode ser executado de novo sem erro.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- Tipos enumerados (os nomes batem com os Enum() do SQLAlchemy)
-- -----------------------------------------------------------------------------

do $$ begin
  create type role as enum ('admin', 'manager', 'supervisor', 'collaborator');
exception when duplicate_object then null; end $$;

do $$ begin
  create type taskstatus as enum ('todo', 'in_progress', 'waiting_client', 'in_review', 'done', 'canceled');
exception when duplicate_object then null; end $$;

do $$ begin
  create type priority as enum ('low', 'normal', 'high', 'urgent');
exception when duplicate_object then null; end $$;

do $$ begin
  create type invitestatus as enum ('pending', 'accepted', 'revoked');
exception when duplicate_object then null; end $$;

-- -----------------------------------------------------------------------------
-- Escritório, departamentos e pessoas
-- -----------------------------------------------------------------------------

create table if not exists organizations (
  id          integer generated by default as identity primary key,
  name        varchar(180) not null,
  created_at  timestamp    not null default (now() at time zone 'utc')
);

create table if not exists departments (
  id               integer generated by default as identity primary key,
  organization_id  integer      not null references organizations (id) on delete cascade,
  name             varchar(120) not null,
  unique (organization_id, name)
);

create table if not exists users (
  id               integer generated by default as identity primary key,
  organization_id  integer      not null references organizations (id) on delete cascade,
  department_id    integer      references departments (id) on delete set null,
  name             varchar(160) not null,
  email            varchar(180) not null,
  password_hash    varchar(255) not null,
  role             role         not null default 'collaborator',
  position         varchar(120) not null default 'Colaborador',
  active           boolean      not null default true
);

-- Mesmo nome do índice gerado pelo SQLAlchemy (index=True, unique=True).
create unique index if not exists ix_users_email on users (lower(email));

create table if not exists invites (
  id               integer generated by default as identity primary key,
  organization_id  integer      not null references organizations (id) on delete cascade,
  token            varchar(64)  not null unique,
  email            varchar(180) not null,
  name             varchar(160) not null,
  position         varchar(120) not null,
  role             role         not null default 'collaborator',
  department_id    integer      references departments (id) on delete set null,
  invited_by       integer      not null references users (id),
  status           invitestatus not null default 'pending',
  created_at       timestamp    not null default (now() at time zone 'utc'),
  expires_at       timestamp    not null,
  accepted_at      timestamp,
  user_id          integer      references users (id) on delete set null
);

-- Um convite pendente por e-mail em cada escritório.
create unique index if not exists ux_invites_pending_email
  on invites (organization_id, lower(email)) where status = 'pending';

-- -----------------------------------------------------------------------------
-- Clientes
-- -----------------------------------------------------------------------------

create table if not exists clients (
  id                 integer generated by default as identity primary key,
  organization_id    integer      not null references organizations (id) on delete cascade,
  internal_owner_id  integer      references users (id) on delete set null,
  legal_name         varchar(180) not null,
  trade_name         varchar(160) not null,
  cnpj               varchar(24)  not null,
  tax_regime         varchar(80)  not null,
  phone              varchar(40),
  email              varchar(180),
  status             varchar(40)  not null default 'active',
  notes              text,
  unique (organization_id, cnpj)
);

-- -----------------------------------------------------------------------------
-- Processos (modelos, etapas e execuções por cliente/competência)
-- -----------------------------------------------------------------------------

create table if not exists process_templates (
  id                 integer generated by default as identity primary key,
  organization_id    integer      not null references organizations (id) on delete cascade,
  department_id      integer      not null references departments (id),
  name               varchar(180) not null,
  description        text,
  -- 0 = prazos no mês da competência; 1 = no mês seguinte.
  due_month_offset   smallint     not null default 1 check (due_month_offset in (0, 1)),
  created_at         timestamp    not null default (now() at time zone 'utc')
);

create table if not exists process_template_steps (
  id           integer generated by default as identity primary key,
  template_id  integer      not null references process_templates (id) on delete cascade,
  title        varchar(180) not null,
  position     integer      not null,
  -- Dia do mês em que a tarefa gerada vence.
  due_day      smallint     not null default 10 check (due_day between 1 and 31)
);

create table if not exists processes (
  id               integer generated by default as identity primary key,
  organization_id  integer      not null references organizations (id) on delete cascade,
  client_id        integer      not null references clients (id),
  template_id      integer      references process_templates (id) on delete set null,
  assignee_id      integer      references users (id) on delete set null,
  creator_id       integer      references users (id) on delete set null,
  name             varchar(180) not null,
  -- Formato MM/AAAA.
  competence       varchar(20)  not null check (competence ~ '^(0[1-9]|1[0-2])/\d{4}$'),
  status           varchar(40)  not null default 'active' check (status in ('active', 'canceled')),
  created_at       timestamp    not null default (now() at time zone 'utc')
);

-- Não inicia o mesmo modelo duas vezes para o mesmo cliente e competência.
create unique index if not exists ux_processes_active
  on processes (template_id, client_id, competence) where status <> 'canceled';

-- -----------------------------------------------------------------------------
-- Tarefas
-- -----------------------------------------------------------------------------

create table if not exists tasks (
  id               integer generated by default as identity primary key,
  organization_id  integer      not null references organizations (id) on delete cascade,
  client_id        integer      not null references clients (id),
  department_id    integer      not null references departments (id),
  assignee_id      integer      not null references users (id),
  reviewer_id      integer      references users (id) on delete set null,
  creator_id       integer      not null references users (id),
  -- Processo que gerou a tarefa (uma tarefa por etapa).
  process_id       integer      references processes (id) on delete set null,
  title            varchar(220) not null,
  description      text,
  due_date         timestamp    not null,
  competence       varchar(20)  not null,
  priority         priority     not null default 'normal',
  status           taskstatus   not null default 'todo',
  created_at       timestamp    not null default (now() at time zone 'utc'),
  updated_at       timestamp    not null default (now() at time zone 'utc'),
  completed_at     timestamp
);

create table if not exists task_checklists (
  id       integer generated by default as identity primary key,
  task_id  integer      not null references tasks (id) on delete cascade,
  title    varchar(180) not null,
  done     boolean      not null default false
);

create table if not exists task_comments (
  id          integer generated by default as identity primary key,
  task_id     integer   not null references tasks (id) on delete cascade,
  author_id   integer   not null references users (id),
  body        text      not null,
  created_at  timestamp not null default (now() at time zone 'utc')
);

create table if not exists task_attachments (
  id           integer generated by default as identity primary key,
  task_id      integer      not null references tasks (id) on delete cascade,
  filename     varchar(180) not null,
  storage_key  varchar(255) not null
);

-- -----------------------------------------------------------------------------
-- Notificações e histórico
-- -----------------------------------------------------------------------------

create table if not exists notifications (
  id               integer generated by default as identity primary key,
  organization_id  integer      not null references organizations (id) on delete cascade,
  user_id          integer      not null references users (id) on delete cascade,
  task_id          integer      references tasks (id) on delete cascade,
  message          varchar(255) not null,
  read             boolean      not null default false,
  created_at       timestamp    not null default (now() at time zone 'utc')
);

create table if not exists activity_logs (
  id               integer generated by default as identity primary key,
  organization_id  integer     not null references organizations (id) on delete cascade,
  actor_id         integer     references users (id) on delete set null,
  task_id          integer     references tasks (id) on delete cascade,
  entity           varchar(80) not null,
  entity_id        integer     not null,
  action           varchar(80) not null,
  detail           text,
  created_at       timestamp   not null default (now() at time zone 'utc')
);

-- -----------------------------------------------------------------------------
-- Índices (chaves estrangeiras e filtros mais usados)
-- -----------------------------------------------------------------------------

create index if not exists ix_departments_org            on departments (organization_id);
create index if not exists ix_users_org                  on users (organization_id);
create index if not exists ix_users_department           on users (department_id);
create index if not exists ix_invites_org                on invites (organization_id);
create index if not exists ix_invites_department         on invites (department_id);
create index if not exists ix_invites_invited_by         on invites (invited_by);
create index if not exists ix_invites_user               on invites (user_id);
create index if not exists ix_clients_organization_id    on clients (organization_id);
create index if not exists ix_clients_owner              on clients (internal_owner_id);
create index if not exists ix_process_templates_org      on process_templates (organization_id);
create index if not exists ix_process_templates_dept     on process_templates (department_id);
create index if not exists ix_process_steps_template     on process_template_steps (template_id, position);
create index if not exists ix_processes_org              on processes (organization_id);
create index if not exists ix_processes_client           on processes (client_id);
create index if not exists ix_processes_assignee         on processes (assignee_id);
create index if not exists ix_processes_creator          on processes (creator_id);
create index if not exists ix_tasks_organization_id      on tasks (organization_id);
create index if not exists ix_tasks_client               on tasks (client_id);
create index if not exists ix_tasks_department           on tasks (department_id);
create index if not exists ix_tasks_assignee             on tasks (assignee_id);
create index if not exists ix_tasks_reviewer             on tasks (reviewer_id);
create index if not exists ix_tasks_creator              on tasks (creator_id);
create index if not exists ix_tasks_process              on tasks (process_id);
create index if not exists ix_tasks_org_due              on tasks (organization_id, due_date);
create index if not exists ix_tasks_org_competence       on tasks (organization_id, competence);
create index if not exists ix_task_checklists_task       on task_checklists (task_id);
create index if not exists ix_task_comments_task         on task_comments (task_id, created_at);
create index if not exists ix_task_comments_author       on task_comments (author_id);
create index if not exists ix_task_attachments_task      on task_attachments (task_id);
create index if not exists ix_notifications_org          on notifications (organization_id);
create index if not exists ix_notifications_user         on notifications (user_id, read, created_at desc);
create index if not exists ix_notifications_task         on notifications (task_id);
create index if not exists ix_activity_logs_org          on activity_logs (organization_id, created_at desc);
create index if not exists ix_activity_logs_actor        on activity_logs (actor_id);
create index if not exists ix_activity_logs_task         on activity_logs (task_id, created_at);

-- -----------------------------------------------------------------------------
-- updated_at automático nas tarefas (equivale ao onupdate do SQLAlchemy,
-- mas vale também para alterações feitas fora do backend)
-- -----------------------------------------------------------------------------

create or replace function set_updated_at() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now() at time zone 'utc';
  return new;
end;
$$;

drop trigger if exists tasks_set_updated_at on tasks;
create trigger tasks_set_updated_at
  before update on tasks
  for each row execute function public.set_updated_at();

-- -----------------------------------------------------------------------------
-- Segurança (Row Level Security)
--
-- Quem acessa o banco é o backend FastAPI, com a connection string do
-- Postgres (usuário `postgres`, que ignora RLS). Ligar RLS sem políticas
-- fecha as tabelas para a API REST pública do Supabase (chaves anon e
-- authenticated); sem isso, qualquer pessoa com a anon key leria os
-- hashes de senha e os dados dos clientes.
-- -----------------------------------------------------------------------------

alter table organizations          enable row level security;
alter table departments            enable row level security;
alter table users                  enable row level security;
alter table invites                enable row level security;
alter table clients                enable row level security;
alter table process_templates      enable row level security;
alter table process_template_steps enable row level security;
alter table processes              enable row level security;
alter table tasks                  enable row level security;
alter table task_checklists        enable row level security;
alter table task_comments          enable row level security;
alter table task_attachments       enable row level security;
alter table notifications          enable row level security;
alter table activity_logs          enable row level security;

-- -----------------------------------------------------------------------------
-- Alembic: marca a migração inicial como aplicada, para que
-- `alembic upgrade head` não tente recriar as tabelas.
-- -----------------------------------------------------------------------------

create table if not exists alembic_version (
  version_num varchar(32) not null primary key
);
alter table alembic_version enable row level security;
insert into alembic_version (version_num) values ('0001_initial') on conflict do nothing;

commit;
